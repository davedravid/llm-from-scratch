"""Phase 6b: synthetic training conversations for the tool-calling model.

Generated by code, fresh for every batch. Most subjects are made-up words, so the model has to learn
to COPY from the request and the tool result rather than memorise answers. Lines the application
provides (the request, "result ...", "error ...") are not graded: the model only learns its own lines.
"""
import json
import random

import tools

CONTEXT = 144   # characters; long enough for the longest generated conversation
HELD_OUT_SUBJECTS = {"fox", "sea", "rabbit", "library", "hen", "owl"}   # never in training
ALL_FACTS = tools.load_facts()
TRAIN_FACTS = {s: f for s, f in ALL_FACTS.items() if s not in HELD_OUT_SUBJECTS}
TAILS = ["was kind", "was brave", "was big and blue", "lived in the sea", "had a hen", "made toys",
         "could talk", "was dark", "had books", "ran away", "was old and wise", "found a shell"]
CONSONANTS, VOWELS = "bcdfghjklmnprstvwz", "aeiou"
CHARSET = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 \n{}\":,.-_/'?!"


def is_held_out_sum(a, b):
    return (7 * a + b) % 10 == 0    # about 1 in 10 number pairs are never used in training


def call_line(tool, **args):
    return json.dumps({"tool": tool, **args}, separators=(",", ":"))


def made_up_word(rng):
    """Half pronounceable, half random letters, so no spelling pattern can stand in for real copying."""
    while True:
        if rng.random() < 0.5:
            word = "".join(rng.choice(CONSONANTS) + rng.choice(VOWELS) for _ in range(rng.randint(1, 4)))
        else:
            word = "".join(rng.choice("abcdefghijklmnopqrstuvwxyz") for _ in range(rng.randint(2, 9)))
        if word not in ALL_FACTS:
            return word


def conversation(rng):
    """One conversation as a list of (text, graded?) pieces."""
    kind = rng.choice(["add", "add", "found", "found", "found", "not_found", "delete_no", "delete_yes", "chat"])
    if kind == "add":
        while is_held_out_sum(a := rng.randint(0, 99), b := rng.randint(0, 99)):
            pass
        return [(f"add {a} and {b}\n", False), (call_line("add", a=a, b=b) + "\n", True),
                (f"result {a + b}\n", False), (f"The answer is {a + b}.\n", True)]
    if kind == "chat":
        text, reply = rng.choice([("hello", "Hello, ask me about a story."), ("sing a song", "I can not help with that."),
                                  ("who are you", "I am a tiny model.")])
        return [(text + "\n", False), (reply + "\n", True)]

    if kind == "found" and rng.random() < 0.3:
        subject, fact = rng.choice(list(TRAIN_FACTS.items()))
    else:
        subject = made_up_word(rng)
        fact = f"The {subject} {rng.choice(TAILS)}."
    if kind == "found":
        return [(f"about the {subject}\n", False), (call_line("lookup", subject=subject) + "\n", True),
                (f"result {fact}\n", False), (fact + "\n", True)]
    if kind == "not_found":
        return [(f"about the {subject}\n", False), (call_line("lookup", subject=subject) + "\n", True),
                ("error not found\n", False), ("I do not know.\n", True)]
    if kind == "delete_no":
        error = rng.choice(["permission denied", "invalid call", "unknown tool"])
        return [(f"delete the {subject}\n", False), (call_line("delete", subject=subject) + "\n", True),
                (f"error {error}\n", False), ("I am not allowed to do that.\n", True)]
    return [(f"delete the {subject}\n", False), (call_line("delete", subject=subject) + "\n", True),
            ("result deleted\n", False), (f"Deleted the {subject}.\n", True)]


def encode_conversation(tokenizer, pieces, ignore=-100):
    """Returns (inputs, targets), with targets ignored wherever the application wrote the text."""
    ids, graded = [], []
    for text, is_graded in pieces:
        piece = tokenizer.encode(text)
        ids += piece
        graded += [is_graded] * len(piece)
    targets = [t if g else ignore for t, g in zip(ids[1:], graded[1:])]
    return ids[:-1], targets


def batch(tokenizer, size, seed):
    rng = random.Random(seed)
    return [encode_conversation(tokenizer, conversation(rng)) for _ in range(size)]


def held_out_requests():
    """(request, expected call, expected final answer, facts available)."""
    rng = random.Random(1234)
    cases = []
    while len(cases) < 20:
        a, b = rng.randint(0, 99), rng.randint(0, 99)
        if is_held_out_sum(a, b):
            cases.append((f"add {a} and {b}", call_line("add", a=a, b=b), f"The answer is {a + b}."))
    for subject in sorted(HELD_OUT_SUBJECTS):
        cases.append((f"about the {subject}", call_line("lookup", subject=subject), ALL_FACTS[subject]))
    for subject in ["moon", "computer", "zebra", "piano"]:
        cases.append((f"about the {subject}", call_line("lookup", subject=subject), "I do not know."))
    for subject in sorted(HELD_OUT_SUBJECTS):
        cases.append((f"delete the {subject}", call_line("delete", subject=subject), "I am not allowed to do that."))
    return cases
